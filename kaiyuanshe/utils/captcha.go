func GenerateCaptchaImage() (answer, imageData string, err error) {
	const alphabet = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ"
	random := make([]byte, 1024)
	if _, err = rand.Read(random); err != nil {
		return "", "", err
	}
	text := make([]byte, 6)
	// alphabet has 32 symbols, so five random bits select without modulo bias.
	for i := range text {
		text[i] = alphabet[int(random[i]&31)]
	}
	canvas := image.NewRGBA(image.Rect(0, 0, 180, 56))
	for y := 0; y < 56; y++ {
		for x := 0; x < 180; x++ {
			canvas.SetRGBA(x, y, color.RGBA{245, 247, 250, 255})
		}
	}
	for i, character := range text {
		glyph := captchaGlyphs[character]
		x0, y0 := 8+i*28, 8+int(random[20+i]%8)
		ink := color.RGBA{uint8(20 + random[40+i]%60), uint8(30 + random[60+i]%70), uint8(60 + random[80+i]%80), 255}
		slant := int(random[100+i]%3) - 1
		for row, line := range glyph {
			for column := 0; column < 5; column++ {
				if line[column] != '1' {
					continue
				}
				for dy := 0; dy < 4; dy++ {
					for dx := 0; dx < 4; dx++ {
						canvas.SetRGBA(x0+column*4+dx+slant*(row-3), y0+row*4+dy, ink)
					}
				}
			}
		}
	}
	for i := 120; i < 720; i += 3 {
		canvas.SetRGBA(int(random[i])%180, int(random[i+1])%56, color.RGBA{120, random[i+2], 170, 255})
	}
	var buffer bytes.Buffer
	if err = png.Encode(&buffer, canvas); err != nil {
		return "", "", err
	}
	return string(text), "data:image/png;base64," + base64.StdEncoding.EncodeToString(buffer.Bytes()), nil
}
